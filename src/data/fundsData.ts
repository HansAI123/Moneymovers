/**
 * Diagnostic logic: evaluates any ticker according to the prompt's exact rules:
 * - Alert Status:
 *   - GREEN: Healthy NAV trend (>= -1.5%) and positive total return.
 *   - YELLOW: Mild NAV erosion (-1.5% to -3.0%), potential payout cut risk.
 *   - RED: Severe NAV erosion (< -3.0%) or unsustainable payout funded by liquidating principal.
 */
export function evaluateFundRules(
  nav_12m: number,
  total_return_12m: number,
  distribution_yield: number,
  category: FundCategory
): {
  alert_status: AlertStatus;
  is_destructive_roc: boolean;
} {
  // If NAV erosion is severe (< -3.0%) or yield is extreme and NAV is collapsing
  const is_destructive =
    nav_12m < -3.0 ||
    (distribution_yield > 25.0 && nav_12m < -1.5) ||
    (total_return_12m < 0 && distribution_yield > 15.0);

  let alert_status: AlertStatus = "GREEN";

  if (nav_12m < -3.0 || is_destructive) {
    alert_status = "RED";
  } else if (nav_12m < -1.5 || total_return_12m <= 0) {
    alert_status = "YELLOW";
  } else {
    alert_status = "GREEN";
  }

  return {
    alert_status,
    is_destructive_roc: is_destructive,
  };
}

/**
 * Calculates compound annual growth rate (CAGR) between two annual dividend payouts
 */
export function calculateDividendCagr(
  startDiv: number,
  endDiv: number,
  years: number
): number | null {
  if (years <= 0 || startDiv <= 0 || endDiv <= 0) return null;
  const cagr = (Math.pow(endDiv / startDiv, 1 / years) - 1) * 100;
  return Math.round(cagr * 10) / 10;
}

/**
 * Classifies dividend payout trajectory based on 3Y and 5Y CAGR and ROC status
 */
export function classifyDividendGrowth(
  cagr3y: number | null,
  cagr5y: number | null,
  isDestructiveRoc: boolean = false
): DividendGrowthClassification {
  if (isDestructiveRoc) {
    return "Declining";
  }
  if (cagr3y === null && cagr5y === null) {
    return "Insufficient History";
  }

  // Prioritize 3Y CAGR, fallback to 5Y
  const primaryCagr = cagr3y !== null ? cagr3y : cagr5y!;

  if (primaryCagr >= 2.0) {
    return "Growing";
  } else if (primaryCagr >= -0.5) {
    return "Stable";
  } else if (primaryCagr >= -2.5) {
    return "Stagnant";
  } else {
    return "Declining";
  }
}

